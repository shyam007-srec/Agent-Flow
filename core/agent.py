import json

from llm.client import LLMClient
from core.tool_registry import ToolRegistry


class Agent:
    def __init__(
        self,
        name: str,
        system_prompt: str,
        llm: LLMClient | None = None,
        tools: ToolRegistry | None = None,
        max_steps: int = 8,
        max_tool_calls: int = 3,
    ):
        self.name = name
        self.system_prompt = system_prompt
        self.llm = llm or LLMClient()
        self.tools = tools or ToolRegistry()

        # Safety limits
        self.max_steps = max_steps
        self.max_tool_calls = max_tool_calls

    def run(self, user_input: str) -> str:

        messages = [
            {
                "role": "system",
                "content": self.system_prompt,
            },
            {
                "role": "user",
                "content": user_input,
            },
        ]

        tool_calls_count = 0

        for step in range(self.max_steps):

            print(f"\n[Agent] Step {step + 1}")

            # -------------------------------------------------
            # Ask the LLM what to do
            # -------------------------------------------------

            response = self.llm.chat(
                messages,
                tools=self.tools.get_openai_tools(),
            )

            # -------------------------------------------------
            # No tool call = final answer
            # -------------------------------------------------

            if not response.tool_calls:

                print("[Agent] Final answer generated.")

                return response.content or ""

            # -------------------------------------------------
            # Add assistant tool-call message
            # -------------------------------------------------

            messages.append(response)

            # -------------------------------------------------
            # Process tool calls
            # -------------------------------------------------

            for tool_call in response.tool_calls:

                tool_calls_count += 1

                tool_name = tool_call.function.name
                raw_arguments = tool_call.function.arguments

                print(
                    f"[Agent] Calling tool: {tool_name}"
                )

                print(
                    f"[Agent] Raw arguments: {raw_arguments}"
                )

                # -------------------------------------------------
                # Maximum tool-call protection
                # -------------------------------------------------

                if tool_calls_count > self.max_tool_calls:

                    print(
                        "[Agent] Maximum tool calls reached."
                    )

                    messages.append(
                        {
                            "role": "system",
                            "content": (
                                "You have reached the maximum "
                                "number of tool calls allowed. "
                                "Do NOT call any more tools. "
                                "Use the information already "
                                "collected and provide the final "
                                "answer to the user."
                            ),
                        }
                    )

                    final_response = self.llm.chat(
                        messages,
                        tools=None,
                    )

                    return final_response.content or ""

                # -------------------------------------------------
                # Parse JSON arguments
                # -------------------------------------------------

                try:

                    arguments = json.loads(
                        raw_arguments
                    )

                except json.JSONDecodeError as exc:

                    raise RuntimeError(
                        f"Invalid JSON generated by the LLM "
                        f"for tool '{tool_name}': "
                        f"{raw_arguments}"
                    ) from exc

                # -------------------------------------------------
                # Validate argument structure
                # -------------------------------------------------

                if not isinstance(arguments, dict):

                    raise RuntimeError(
                        f"Tool arguments must be a JSON object. "
                        f"Received: {arguments}"
                    )

                print(
                    f"[Agent] Parsed arguments: {arguments}"
                )

                # -------------------------------------------------
                # Execute tool
                # -------------------------------------------------

                try:

                    result = self.tools.execute(
                        tool_name,
                        arguments,
                    )

                except Exception as exc:

                    print(
                        f"[Agent] Tool '{tool_name}' failed: "
                        f"{exc}"
                    )

                    result = {
                        "error": str(exc),
                        "tool": tool_name,
                    }

                # -------------------------------------------------
                # Print result status
                # -------------------------------------------------

                print(
                    "[Agent] Tool result received."
                )

                # -------------------------------------------------
                # Send tool result back to LLM
                # -------------------------------------------------

                messages.append(
                    {
                        "role": "tool",
                        "tool_call_id": tool_call.id,
                        "name": tool_name,
                        "content": json.dumps(
                            result,
                            ensure_ascii=False,
                        ),
                    }
                )

        # ---------------------------------------------------------
        # Maximum reasoning steps reached
        # ---------------------------------------------------------

        print(
            "[Agent] Maximum steps reached. "
            "Requesting final answer."
        )

        messages.append(
            {
                "role": "system",
                "content": (
                    "You have reached the maximum reasoning "
                    "steps. Do NOT use any more tools. "
                    "Provide the best possible final answer "
                    "using the information already collected."
                ),
            }
        )

        final_response = self.llm.chat(
            messages,
            tools=None,
        )

        return final_response.content or ""